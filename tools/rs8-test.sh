#!/bin/bash
# Check the shim's Reed-Solomon encoder against the kernel's own.
#
# The reference is not a re-implementation: rs_init() and the encode_rs8()
# body are extracted verbatim from the phone's kernel tree, so a mistake in
# shim/rs8.c shows up here as a difference.
#
#   tools/rs8-test.sh [path-to-kernel-tree]
set -euo pipefail
cd "$(dirname "$0")/.."

KT=${1:-"/Users/io/Dev/ios/lg g4/G4-Titan-Kernel-titan_bpf2"}
[ -d "$KT/lib/reed_solomon" ] || { echo "no kernel tree at $KT" >&2; exit 1; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# The kernel's rs_init(), verbatim.
sed -n '/^static struct rs_control \*rs_init/,/^}/p' "$KT/lib/reed_solomon/reed_solomon.c" \
	> "$TMP/rs_init.c"
# The kernel's encode_rs8() body, verbatim: it is a fragment meant to be
# included inside a function that has rs/data/len/par/invmsk in scope.
sed -n '/^{/,$p' "$KT/lib/reed_solomon/encode_rs.c" > "$TMP/encode_body.c"

cat > "$TMP/ref.c" <<'EOF'
/* Generated by tools/rs8-test.sh: the kernel's encoder, verbatim. */
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <stdio.h>

#define ERANGE 34
#define kmalloc(n, f) malloc(n)
#define kfree(p) free(p)

#define INIT_LIST_HEAD(ptr) do { (ptr)->next = (ptr); (ptr)->prev = (ptr); } while (0)

#include "rsctl.h"

static inline int rs_modnn(struct rs_control *rs, int x)
{
	while (x >= rs->nn) {
		x -= rs->nn;
		x = (x >> rs->mm) + (x & rs->nn);
	}
	return x;
}

#include "rs_init.c"

static int ref_encode_rs8(struct rs_control *rs, uint8_t *data, int len,
			   uint16_t *par, uint16_t invmsk)
{
#include "encode_body.c"
}
EOF

cat > "$TMP/rsctl.h" <<'EOF'
#ifndef RSCTL_H
#define RSCTL_H
#include <stdint.h>
struct list_head { struct list_head *next, *prev; };
struct rs_control {
	int mm, nn, nroots, fcr, prim, iprim, gfpoly;
	uint16_t *alpha_to, *index_of, *genpoly;
	int (*gffunc)(int);
	struct list_head list;
};
#endif
EOF

cat > "$TMP/main.c" <<'EOF'
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include "rsctl.h"

#include "ref.c"

/* From shim/rs8.c */
void rs8_init(void);
int rs8_encode(const uint8_t *data, int len, uint8_t *ecc);

int main(void)
{
	struct rs_control *rs = rs_init(8, 0x11d, NULL, 0, 1, 16);
	uint8_t buf[512], ecc[16], re[16];
	uint16_t par[16];
	int fail = 0;

	if (!rs) {
		printf("rs_init failed\n");
		return 1;
	}
	srandom(12345);
	for (int len = 0; len <= 239; len++) {
		for (int trial = 0; trial < 40; trial++) {
			for (int i = 0; i < len; i++)
				buf[i] = (uint8_t)(random() & 0xff);
			memset(par, 0, sizeof(par));
			ref_encode_rs8(rs, buf, len, par, 0);
			for (int i = 0; i < 16; i++)
				re[i] = (uint8_t)par[i];
			rs8_encode(buf, len, ecc);
			if (memcmp(ecc, re, 16)) {
				printf("MISMATCH len=%d trial=%d\n", len, trial);
				for (int i = 0; i < 16; i++)
					printf("  %02x vs %02x%s", ecc[i], re[i],
					       (i % 8 == 7) ? "\n" : " ");
				if (++fail > 5)
					return 1;
			}
		}
	}
	/* The two lengths that matter on the phone: the 12 byte zone header
	 * and a full 128 byte ECC block. */
	printf("header  : ");
	rs8_init();
	rs8_encode((const uint8_t *)"0123456789ab", 12, ecc);
	for (int i = 0; i < 16; i++) printf("%02x", ecc[i]);
	printf("\n");
	printf("%s\n", fail ? "FAIL" : "OK: the shim's encoder matches the kernel's");
	return fail ? 1 : 0;
}
EOF

cc -O1 -Wall -I"$TMP" -o "$TMP/rs8-test" "$TMP/main.c" "$TMP/ref.c" shim/rs8.c
"$TMP/rs8-test"
