EOF

cat > "$TMP/main.c" <<'EOF'
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

#include "ref.c"

/* The whole ramoops region: 1 MiB, as on the phone. The console zone is
 * not at the start of it: the twelve record zones come first. */
static uint8_t region[0x100000];
static struct rs_control *rs;

/* The shim's writer, with the zone moved into this process. */
#define PSTORE_HAVE_MEMCPY 1
#define PSTORE_NO_CONSOLE 1
#define RAMOOPS_BASE ((uintptr_t)region)
#define RAMOOPS_BASE2 0
#include "pstore.c"

#define ZHDR	(region)
#define ZDATA	(ZHDR + 12)
#define ZDATA_SZ	116468
#define ZPAR	(ZDATA + ZDATA_SZ)
#define ZPAR_HDR	(ZPAR + 911 * 16)

static uint32_t rd32(const uint8_t *p)
{
	uint32_t v;

	memcpy(&v, p, 4);
	return v;
}

static void wr32(uint8_t *p, uint32_t v)
{
	memcpy(p, &v, 4);
}

/* The kernel's persistent_ram_update_ecc(): the parity of every 128 byte
 * block the write touched. */
static void kernel_ecc(unsigned start, unsigned count)
{
	unsigned b = start / 128;

	while (b * 128 < start + count) {
		unsigned blen = ZDATA_SZ - b * 128;
		uint16_t par[16];
		uint8_t ecc[16];

		if (blen > 128)
			blen = 128;
		memset(par, 0, sizeof(par));
		ref_encode_rs8(rs, ZDATA + b * 128, (int)blen, par, 0);
		for (int i = 0; i < 16; i++)
			ecc[i] = (uint8_t)par[i];
		memcpy(ZPAR + b * 16, ecc, 16);
		b++;
	}
}

/* The kernel's persistent_ram_write(), reduced to what a console does. */
static void kernel_write(const char *s, unsigned n)
{
	uint32_t start = rd32(ZHDR + 4);
	uint32_t size = rd32(ZHDR + 8);
	unsigned first = n;

	if (start + n > ZDATA_SZ) {
		first = ZDATA_SZ - start;
		memcpy(ZDATA + start, s, first);
		memcpy(ZDATA, s + first, n - first);
	} else {
		memcpy(ZDATA + start, s, n);
	}
	kernel_ecc(start, n);
	start = (start + n) % ZDATA_SZ;
	size += n;
	if (size > ZDATA_SZ)
		size = ZDATA_SZ;
	wr32(ZHDR + 4, start);
	wr32(ZHDR + 8, size);
}

/* The kernel's persistent_ram_save_old(). */
static uint8_t old_log[0x20000];
static unsigned old_log_size;

static void kernel_save_old(void)
{
	uint32_t start = rd32(ZHDR + 4);
	uint32_t size = rd32(ZHDR + 8);

	if (size > ZDATA_SZ)
		size = ZDATA_SZ;
	if (start > ZDATA_SZ)
		start = 0;
	if (size >= start) {
		memcpy(old_log, ZDATA + start, size - start);
		memcpy(old_log + size - start, ZDATA, start);
	} else {
		memcpy(old_log, ZDATA + start, size);
	}
	old_log_size = size;
}

int main(void)
{
	rs = rs_init(8, 0x11d, NULL, 0, 1, 16);
	char payload[4096];
	int fail = 0;
	int found = 0;

	if (!rs) {
		printf("rs_init failed\n");
		return 1;
	}
	/* A zone as the kernel leaves it: the signature, an empty ring. */
	wr32(ZHDR, 0x43474244u);
	wr32(ZHDR + 4, 0);
	wr32(ZHDR + 8, 0);

	/* The console log of the previous boot, as the kernel wrote it. */
	kernel_write("[    0.000000] previous boot console log\n", 41);

	/* The shim's record. */
	for (int i = 0; i < (int)sizeof(payload); i++)
		payload[i] = (char)('A' + (i % 26));
	pstore_console_write(payload, sizeof(payload));

	/* What the kernel reads back. */
	kernel_save_old();
	printf("old_log: %u bytes\n", old_log_size);
	if (old_log_size < 100) {
		printf("FAIL: the kernel would read nothing\n");
		return 1;
	}
	/* The record has to be in it. */
	for (unsigned i = 0; i + 7 < old_log_size; i++) {
		if (!memcmp(old_log + i, "[G4SHIM", 7)) {
			found = 1;
			printf("record found at offset %u\n", i);
			break;
		}
	}
	if (!found) {
		printf("FAIL: the record is not in what the kernel reads back\n");
		fail = 1;
	}
	/* And the payload has to be intact: the CRC in the header says so.
	 * The length is decimal, the CRC is hexadecimal. */
	{
		char *p = strstr((char *)old_log, "[G4SHIMPS1] len=");
		unsigned len = 0, crc = 0, mine = 0;

		if (p) {
			len = (unsigned)strtoul(strstr(p, "len=") + 4, NULL, 10);
			crc = (unsigned)strtoul(strstr(p, "crc=") + 4, NULL, 16);
			printf("record: len=%u crc=%08x\n", len, crc);
			/* The CRC of the payload, the same way the host does it. */
			{
				const char *body = strchr(p, '\n') + 1;
				uint32_t c = 0xffffffffu;
				const uint8_t *q = (const uint8_t *)body;

				for (unsigned i = 0; i < len; i++) {
					c ^= q[i];
					for (int b = 0; b < 8; b++)
						c = (c >> 1) ^ (0xedb88320u & (-(int32_t)(c & 1)));
				}
				mine = ~c;
			}
			if (mine != crc) {
				printf("FAIL: the CRC in the header is %08x, the payload says %08x\n",
				       crc, mine);
				fail = 1;
			} else {
				printf("crc: ok\n");
			}
		} else {
			printf("FAIL: no record header in what the kernel reads back\n");
			fail = 1;
		}
	}
	/* The parity of every block has to be right: the kernel's decoder
	 * would otherwise "correct" the data. */
	{
		uint8_t hdr_copy[12];
		uint16_t par[16];
		int err;

		memcpy(hdr_copy, ZHDR, 12);
		for (int i = 0; i < 16; i++)
			par[i] = ZPAR_HDR[i];
		err = ref_decode_rs8(rs, hdr_copy, par, 12, NULL, 0, NULL, 0, NULL);
		if (err != 0) {
			printf("FAIL: the header parity is wrong (decoder says %d)\n", err);
			fail = 1;
		} else if (memcmp(hdr_copy, ZHDR, 12)) {
			printf("FAIL: the decoder changed the header\n");
			fail = 1;
		} else {
			printf("header parity: ok\n");
		}
		for (unsigned b = 0; b * 128 < ZDATA_SZ; b++) {
			unsigned blen = ZDATA_SZ - b * 128;
			uint8_t copy[128];

			if (blen > 128)
				blen = 128;
			memcpy(copy, ZDATA + b * 128, blen);
			for (int i = 0; i < 16; i++)
				par[i] = (uint16_t)(ZPAR + b * 16)[i];
			err = ref_decode_rs8(rs, copy, par, (int)blen, NULL, 0, NULL, 0, NULL);
			if (err != 0) {
				printf("FAIL: block %u has a wrong parity (%d)\n", b, err);
				fail = 1;
				break;
			}
			if (memcmp(copy, ZDATA + b * 128, blen)) {
				printf("FAIL: the decoder changed block %u\n", b);
				fail = 1;
				break;
			}
		}
		if (!fail)
			printf("every block: parity ok, data unchanged\n");
	}
	printf("%s\n", fail ? "FAIL" : "OK: the shim's writer leaves the zone as the kernel expects it");
	return fail;
}
EOF

cc -O1 -g -Wall -I"$TMP" -Ishim -o "$TMP/pstore-test" "$TMP/main.c" "$TMP/ref.c" shim/rs8.c
"$TMP/pstore-test"
