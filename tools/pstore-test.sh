#!/bin/bash
# Check the shim's ramoops writer against the kernel's own reader.
#
# The test builds a fake console zone, lets the shim write a record into it
# and then does what the kernel does when it boots:
#
#   - persistent_ram_save_old(): copy the ring back, from start, wrapping;
#   - persistent_ram_decode_rs8(): check every block against its parity,
#     with the kernel's own Reed-Solomon decoder.
#
# If the record comes back whole and the decoder finds no error in any
# block, the writer leaves the zone exactly as the kernel expects it.
#
#   tools/pstore-test.sh [path-to-kernel-tree]
set -euo pipefail
cd "$(dirname "$0")/.."

KT=${1:-"/Users/io/Dev/ios/lg g4/G4-Titan-Kernel-titan_bpf2"}
[ -d "$KT/lib/reed_solomon" ] || { echo "no kernel tree at $KT" >&2; exit 1; }

TMP=$(mktemp -d)
if [ -n "${KEEP:-}" ]; then
	echo "work dir: $TMP"
else
	trap 'rm -rf "$TMP"' EXIT
fi

sed -n '/^static struct rs_control \*rs_init/,/^}/p' "$KT/lib/reed_solomon/reed_solomon.c" \
	> "$TMP/rs_init.c"
sed -n '/^{/,$p' "$KT/lib/reed_solomon/encode_rs.c" > "$TMP/encode_body.c"
sed -n '/^{/,$p' "$KT/lib/reed_solomon/decode_rs.c" > "$TMP/decode_body.c"

cat > "$TMP/rsctl.h" <<'EOF'
#ifndef RSCTL_H
#define RSCTL_H
#include <stdint.h>
struct list_head { struct list_head *next, *prev; };
struct rs_control {
	int mm, nn, nroots, fcr, prim, iprim, gfpoly;
	uint16_t *alpha_to, *index_of, *genpoly;
	int (*gffunc)(int);
	struct list_head list;
};
#endif
EOF

cat > "$TMP/ref.c" <<'EOF'
/* Generated by tools/pstore-test.sh: the kernel's encoder and decoder. */
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <stdio.h>

#define ERANGE 34
#define EBADMSG 74
#define min(a, b) ((a) < (b) ? (a) : (b))
#define BUG_ON(x) do { if (x) { fprintf(stderr, "BUG_ON at %s:%d\n", __FILE__, __LINE__); exit(2); } } while (0)
#define kmalloc(n, f) malloc(n)
#define kfree(p) free(p)
#define INIT_LIST_HEAD(ptr) do { (ptr)->next = (ptr); (ptr)->prev = (ptr); } while (0)

#include "rsctl.h"

static inline int rs_modnn(struct rs_control *rs, int x)
{
	while (x >= rs->nn) {
		x -= rs->nn;
		x = (x >> rs->mm) + (x & rs->nn);
	}
	return x;
}

#include "rs_init.c"

static int ref_encode_rs8(struct rs_control *rs, uint8_t *data, int len,
			   uint16_t *par, uint16_t invmsk)
{
